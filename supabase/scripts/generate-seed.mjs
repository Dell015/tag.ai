// One-off seed generator for Stage B (docs/DATABASE_SPEC.md).
// Reads the card, topic, deck and shop data the app already ships and writes
// supabase/seed/002_stage_b_seed.sql, keeping every id players may have saved.
//
// Run from the repo root: node supabase/scripts/generate-seed.mjs
// Uses the project's own Vite (already a dev dependency through Vitest) to load the TypeScript files.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createServer } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = path.join(root, 'src');

const vite = await createServer({
  configFile: false,
  root,
  logLevel: 'error',
  appType: 'custom',
  server: { middlewareMode: true, hmr: false, ws: false },
  optimizeDeps: { noDiscovery: true, include: [] },
  resolve: { alias: { '@': src } },
});
const load = (p) => vite.ssrLoadModule(path.join(src, p));

const { CURATED_CARDS } = await load('lib/data/cards.ts');
const { TOOL_CARDS, ADULT_TOOL_CARDS } = await load('lib/data/tool-cards.ts');
const { ADULT_CARDS } = await load('lib/data/adult-cards.ts');
const { TALK_TOPICS, formatOf } = await load('lib/data/talk-topics.ts');
const { SHOP_ITEMS } = await load('lib/data/shop-catalogue.ts');
const { DECKS } = await load('lib/game/decks.ts');
const { kindOf } = await load('lib/game/card-kinds.ts');
await vite.close();

// ---------- SQL helpers ----------
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === null || v === undefined ? 'null' : String(Number(v)));
const bool = (v) => (v ? 'true' : 'false');
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;
const compact = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined && v !== null));

// ---------- Curated cards: cards.ts is what players see; cards.sql keeps retired id slots ----------
const sql = readFileSync(path.join(root, 'supabase', 'seed', 'cards.sql'), 'utf8');
const re = /^\('((?:[^']|'')*)', '(\w+)', (\d), '(\w+)', ARRAY\[([^\]]*)\], '(\w+)', NULL, (true|false)\)[,;]?\s*$/;
const seedRows = [];
for (const line of sql.split(/\r?\n/)) {
  const m = line.match(re);
  if (!m) continue;
  const [, text, cardType, intensity, category, topics] = m;
  seedRows.push({
    id: `card-${String(seedRows.length + 1).padStart(3, '0')}`,
    text: text.replace(/''/g, "'"),
    cardType,
    intensity: Number(intensity),
    category,
    topics: [...topics.matchAll(/'([^']+)'/g)].map((t) => t[1]),
  });
}
const liveIds = new Set(CURATED_CARDS.map((c) => c.id));
const retired = seedRows.filter((r) => !liveIds.has(r.id));

const cards = [];
const addCard = (c, { status = 'approved', deckId = null } = {}) => {
  const extra = compact({ tool: c.tool, outcomes: c.outcomes, rule: c.rule, penalty: c.penalty, people: c.people });
  cards.push({
    id: c.id, text: c.text, kind: kindOf(c), card_type: c.cardType, intensity: c.intensity, category: c.category,
    topics: c.topics ?? [], deck_id: deckId, adult: !!c.adult, wild_type: c.wildCardType ?? null, status, extra,
  });
};
CURATED_CARDS.forEach((c) => addCard(c));
retired.forEach((c) => addCard(c, { status: 'retired' }));
TOOL_CARDS.forEach((c) => addCard(c));
ADULT_CARDS.forEach((c) => addCard(c, { deckId: 'adult' }));
ADULT_TOOL_CARDS.forEach((c) => addCard(c, { deckId: 'adult' }));

const ids = new Set();
for (const c of cards) {
  if (ids.has(c.id)) throw new Error(`Duplicate card id ${c.id}`);
  ids.add(c.id);
}

// ---------- Output ----------
const out = [];
out.push(`-- GENERATED by supabase/scripts/generate-seed.mjs. Do not edit by hand; rerun the script.
-- Seeds decks, cards, talk_topics and shop_items. Safe to rerun (upserts on id).
-- Counts: ${DECKS.length} decks, ${cards.length} cards (${CURATED_CARDS.length} curated, ${retired.length} retired, ${TOOL_CARDS.length} tool, ${ADULT_CARDS.length} adult, ${ADULT_TOOL_CARDS.length} adult tool), ${TALK_TOPICS.length} topics, ${SHOP_ITEMS.length} shop items.

begin;
`);

out.push(`insert into public.decks (id, name, blurb, price, ready, adult, includes_adult) values
${DECKS.map((d) => `  (${q(d.id)}, ${q(d.name)}, ${q(d.blurb)}, ${num(d.price)}, ${bool(d.ready)}, ${bool(d.adult)}, ${bool(d.includesAdult)})`).join(',\n')}
on conflict (id) do update set name = excluded.name, blurb = excluded.blurb, price = excluded.price,
  ready = excluded.ready, adult = excluded.adult, includes_adult = excluded.includes_adult;
`);

out.push(`insert into public.cards (id, text, kind, card_type, intensity, category, topics, deck_id, adult, wild_type, status, source, extra) values
${cards.map((c) => `  (${q(c.id)}, ${q(c.text)}, ${q(c.kind)}, ${q(c.card_type)}, ${c.intensity}, ${q(c.category)}, ${arr(c.topics)}, ${q(c.deck_id)}, ${bool(c.adult)}, ${q(c.wild_type)}, ${q(c.status)}, 'seed', ${json(c.extra)})`).join(',\n')}
on conflict (id) do update set text = excluded.text, kind = excluded.kind, card_type = excluded.card_type,
  intensity = excluded.intensity, category = excluded.category, topics = excluded.topics, deck_id = excluded.deck_id,
  adult = excluded.adult, wild_type = excluded.wild_type, status = excluded.status, extra = excluded.extra;
`);

out.push(`insert into public.talk_topics (id, "group", format, text, deeper, a, b, topics, status) values
${TALK_TOPICS.map((t) => `  (${q(t.id)}, ${q(t.group)}, ${q(formatOf(t))}, ${q(t.text)}, ${q(t.deeper)}, ${q(t.a)}, ${q(t.b)}, ${arr(t.topics)}, 'approved')`).join(',\n')}
on conflict (id) do update set "group" = excluded."group", format = excluded.format, text = excluded.text,
  deeper = excluded.deeper, a = excluded.a, b = excluded.b, topics = excluded.topics;
`);

out.push(`insert into public.shop_items (id, kind, name, price, description, value, adult, active) values
${SHOP_ITEMS.map((s) => `  (${q(s.id)}, ${q(s.kind)}, ${q(s.name)}, ${num(s.price)}, ${q(s.description)}, ${q(s.value)}, ${bool(s.adult)}, true)`).join(',\n')}
on conflict (id) do update set kind = excluded.kind, name = excluded.name, price = excluded.price,
  description = excluded.description, value = excluded.value, adult = excluded.adult;
`);

out.push('commit;\n');

const file = path.join(root, 'supabase', 'seed', '002_stage_b_seed.sql');
writeFileSync(file, out.join('\n'));
console.log(`Wrote ${path.relative(root, file)}: ${DECKS.length} decks, ${cards.length} cards (${retired.length} retired: ${retired.map((r) => r.id).join(', ')}), ${TALK_TOPICS.length} topics, ${SHOP_ITEMS.length} shop items`);
