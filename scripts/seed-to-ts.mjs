// Regenerates src/lib/data/cards.ts from supabase/seed/cards.sql.
// Run: node scripts/seed-to-ts.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const sql = readFileSync(new URL('../supabase/seed/cards.sql', import.meta.url), 'utf8');
const re = /^\('((?:[^']|'')*)', '(\w+)', (\d), '(\w+)', ARRAY\[([^\]]*)\], '(\w+)', NULL, true\)[,;]?\s*$/;

const cards = [];
for (const line of sql.split('\n')) {
  const m = line.match(re);
  if (!m) continue;
  const [, text, cardType, intensity, category, topics, audience] = m;
  cards.push({
    id: `card-${String(cards.length + 1).padStart(3, '0')}`,
    text: text.replace(/''/g, "'"),
    cardType,
    intensity: Number(intensity),
    category,
    topics: [...topics.matchAll(/'([^']+)'/g)].map((t) => t[1]),
    audience,
  });
}

const out = `// GENERATED by scripts/seed-to-ts.mjs from supabase/seed/cards.sql — do not edit by hand.
import type { QueuedCard } from '@/lib/game/escalation-engine';

export const CURATED_CARDS: QueuedCard[] = ${JSON.stringify(
  cards.map(({ audience, ...c }) => c),
  null,
  2
)};
`;
writeFileSync(new URL('../src/lib/data/cards.ts', import.meta.url), out);
console.log(`Wrote ${cards.length} cards`);
